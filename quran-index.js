function findQuranVerses(root) {
  if (!root || root.length < 2) return [];

  // ١. بحث مباشر
  if (QURAN_BY_ROOT[root]) return QURAN_BY_ROOT[root];

  // ٢. بحث بالحرفين الأولين
  const short = root.substring(0, 2);
  if (QURAN_BY_ROOT[short]) return QURAN_BY_ROOT[short];

  // ٣. بحث بثلاثة حروف
  const three = root.substring(0, 3);
  if (QURAN_BY_ROOT[three]) return QURAN_BY_ROOT[three];

  // ٤. بحث فضفاض
  for (const key in QURAN_BY_ROOT) {
    if (key.indexOf(short) === 0) return QURAN_BY_ROOT[key];
    if (short.indexOf(key.substring(0, 2)) === 0) return QURAN_BY_ROOT[key];
  }

  return [];
}

function renderQuranVersesHTML(verses, root) {
  if (!verses || verses.length === 0) {
    return '<div class="card quran-card">' +
      '<div class="card-title">📖 الآيات القرآنية</div>' +
      '<p style="font-size:13.5px;color:#888;text-align:center;padding:16px 0">' +
      'لم يُعثر على آيات لهذا الجذر في الفهرس الحالي.<br>' +
      '<span style="font-size:12px">(الفهرس يحتوي على 200+ جذر قرآني)</span>' +
      '</p></div>';
  }

  const versesHTML = verses.map(function(v, i) {
    return '<div class="quran-verse">' +
      '<div class="quran-verse-num">' + (i + 1) + '</div>' +
      '<div class="quran-verse-text">﴿ ' + v.t + ' ﴾</div>' +
      '<div class="quran-verse-ref">سورة ' + v.s + ' • الآية ' + v.a + '</div>' +
      '</div>';
  }).join("");

  return '<div class="card quran-card">' +
    '<div class="card-title">📖 الآيات القرآنية التي ورد فيها الجذر «' + root + '»</div>' +
    '<p style="font-size:12.5px;color:#666;margin-bottom:12px;line-height:1.8">' +
    verses.length + ' آية تدل على السياق القرآني لهذا الجذر.' +
    '</p>' + versesHTML + '</div>';
}